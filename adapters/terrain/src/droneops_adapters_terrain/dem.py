"""DEM clipping interface with the provenance the manifest needs (spec 12 section 5).

What is stored, and why each one is mandatory:

* ``raster_version`` - Copernicus GLO-30 has editions; a re-download changes the numbers.
* ``vertical_datum`` - without it, "elevation 326 m" is above nothing. Ellipsoid
  (WGS 84) and geoid (EGM2008/MSL) differ in northern India by roughly 30 m, which is
  larger than the synthetic obstacle margins this project uses. An undeclared datum
  makes the clip *unusable for clearance*, and this module says so instead of assuming.
* ``resolution_m`` - the grid step, recorded because it bounds what the surface can show.
* ``source`` and ``retrieval_date`` - a DEM is a snapshot of a licensed product, and the
  licence (Copernicus CC-BY-SA / NASA USGS public domain) travels with it. This adapter
  never fetches one; the operator supplies a path to a raster they are entitled to use.
* ``clipping_method`` - bbox crop plus polygon mask plus nodata fill changes statistics;
  a clip from two different methods is not comparable.

The caveat that must never be dropped: a 30 m grid cannot represent a tower, a wire or
a rooftop. Terrain is the ground, obstacles are what stands on it, and a route planner
that only has the ground believes it has both.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np
import yaml
from shapely.geometry import shape
from shapely.geometry.base import BaseGeometry

from .errors import TerrainError, VerticalDatumError
from .geotiff import read_geotiff, write_geotiff

TERRAIN_CAVEAT = (
    "A 30 m DEM cannot represent a tower, a wire or a rooftop. This raster is the ground "
    "surface only; obstacle clearance is not a terrain question and must not be derived "
    "from it."
)

CLIPPING_METHODS = {"bbox-crop", "polygon-mask-bbox-crop", "polygon-mask-cells-centre"}


@dataclass
class TerrainRecord:
    """What was clipped, from where, and how far it can be trusted."""

    source: str
    raster_version: str
    vertical_datum: str
    datum_declared: bool
    resolution_m: float
    retrieval_date: str
    clipping_method: str
    raster_sha256: str
    clip_sha256: str
    raster_path: str
    clip_path: str
    bbox_deg: list[float]
    width_cells: int
    height_cells: int
    valid_cells: int
    masked_cells: int
    elevation_min_m: float | None
    elevation_max_m: float | None
    elevation_mean_m: float | None
    nodata: float | None
    geo_ascii_params: str
    usable_for_clearance: bool
    caveat: str
    note: str = ""
    extra: dict[str, Any] = field(default_factory=dict)

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)

    def write(self, path: Path) -> str:
        path.parent.mkdir(parents=True, exist_ok=True)
        text = yaml.safe_dump(self.as_dict(), sort_keys=False, allow_unicode=True, width=100)
        body = (
            "# DroneOps terrain clip record. Generated by adapters/terrain.\n"
            "# Simulation only. Not authorised for flight.\n" + text
        )
        path.write_text(body, encoding="utf-8")
        from .hashing import sha256_of_file

        return sha256_of_file(path)


def load_polygon(path: Path) -> BaseGeometry:
    """Read a boundary polygon from GeoJSON (Feature, FeatureCollection or geometry)."""
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    if payload.get("type") == "FeatureCollection":
        features = payload.get("features") or []
        if not features:
            raise TerrainError(f"{path}: FeatureCollection with no features")
        payload = features[0]
    if payload.get("type") == "Feature":
        payload = payload.get("geometry") or {}
    if not payload.get("coordinates"):
        raise TerrainError(f"{path}: no polygon coordinates found")
    return shape(payload)


def read_raster(path: Path) -> Any:
    """Read a local raster: GeoTIFF, or an .npz array with a georeferencing sidecar."""
    path = Path(path)
    if path.suffix.lower() in {".tif", ".tiff"}:
        return read_geotiff(path)
    if path.suffix.lower() in {".npz", ".npy"}:
        sidecar = path.with_suffix(".yaml")
        if not sidecar.is_file():
            raise TerrainError(
                f"{path}: a raw array needs a georeferencing sidecar {sidecar.name} with "
                "origin_x, origin_y, pixel_size_x, pixel_size_y and (optionally) nodata. "
                "An un-anchored grid is not a terrain model."
            )
        meta = yaml.safe_load(sidecar.read_text(encoding="utf-8"))
        array = np.load(path)
        data = array["data"] if isinstance(array, np.lib.npyio.NpzFile) else array
        return _NpRaster(
            data=np.asarray(data, dtype=np.float32),
            origin_x=float(meta["origin_x"]),
            origin_y=float(meta["origin_y"]),
            pixel_size_x=float(meta["pixel_size_x"]),
            pixel_size_y=float(meta["pixel_size_y"]),
            nodata=float(meta["nodata"]) if meta.get("nodata") is not None else None,
            geo_ascii_params=str(meta.get("geo_ascii_params", "")),
            path=str(path),
        )
    raise TerrainError(f"{path}: unsupported raster type; use .tif or .npz plus a .yaml sidecar")


class _NpRaster:
    """Duck-typed stand-in for :class:`~.geotiff.GeoTiff` for array-plus-sidecar input."""

    def __init__(
        self,
        *,
        data: np.ndarray,
        origin_x: float,
        origin_y: float,
        pixel_size_x: float,
        pixel_size_y: float,
        nodata: float | None,
        geo_ascii_params: str,
        path: str,
    ) -> None:
        self.data = data
        self.width = data.shape[1]
        self.height = data.shape[0]
        self.origin_x = origin_x
        self.origin_y = origin_y
        self.pixel_size_x = pixel_size_x
        self.pixel_size_y = pixel_size_y
        self.nodata = nodata
        self.geo_ascii_params = geo_ascii_params
        self.path = path

    def bbox(self) -> tuple[float, float, float, float]:
        return (
            self.origin_x,
            self.origin_y - abs(self.pixel_size_y) * self.height,
            self.origin_x + abs(self.pixel_size_x) * self.width,
            self.origin_y,
        )


def clip_dem(
    raster_path: Path,
    polygon_path: Path,
    out_dir: Path,
    *,
    source: str,
    raster_version: str,
    vertical_datum: str,
    resolution_m: float,
    retrieval_date: str | None = None,
    clipping_method: str = "polygon-mask-bbox-crop",
) -> TerrainRecord:
    """Crop a raster to a boundary polygon and record exactly how that was done."""
    if clipping_method not in CLIPPING_METHODS:
        raise TerrainError(
            f"unknown clipping method {clipping_method!r}; choose from {sorted(CLIPPING_METHODS)}"
        )
    raster = read_raster(Path(raster_path))
    mask = load_polygon(Path(polygon_path))
    left, bottom, right, top = mask.bounds
    raster_left, raster_bottom, raster_right, raster_top = raster.bbox()
    if raster_right <= left or raster_left >= right or raster_top <= bottom or raster_bottom >= top:
        raise TerrainError(
            f"the polygon ({left:.4f},{bottom:.4f},{right:.4f},{top:.4f}) does not touch the "
            f"raster ({raster_left:.4f},{raster_bottom:.4f},{raster_right:.4f},{raster_top:.4f}). "
            "A clip of nothing would be written as a terrain surface for Chandigarh, which "
            "is exactly the sort of artefact that gets mistaken for coverage."
        )

    col_start = max(0, int((left - raster_left) / abs(raster.pixel_size_x)))
    col_end = min(raster.width, int((right - raster_left) / abs(raster.pixel_size_x)) + 2)
    row_start = max(0, int((raster_top - top) / abs(raster.pixel_size_y)))
    row_end = min(raster.height, int((raster_top - bottom) / abs(raster.pixel_size_y)) + 2)
    crop = np.array(raster.data[row_start:row_end, col_start:col_end], dtype=np.float32)
    origin_x = raster.origin_x + col_start * raster.pixel_size_x
    origin_y = raster.origin_y + row_start * raster.pixel_size_y

    nodata = -9999.0
    if clipping_method != "bbox-crop":
        crop = _apply_polygon_mask(
            crop, mask, origin_x, origin_y, raster.pixel_size_x, raster.pixel_size_y, nodata,
            centre_only=clipping_method == "polygon-mask-cells-centre",
        )
    valid = crop[crop != nodata]
    masked = int(crop.size - valid.size)

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    clip_path = out_dir / "dem_clip.tif"
    write_geotiff(
        clip_path,
        crop,
        origin_x=origin_x,
        origin_y=origin_y,
        pixel_size_x=raster.pixel_size_x,
        pixel_size_y=raster.pixel_size_y,
        nodata=nodata,
        geo_ascii=raster.geo_ascii_params or 'GEOGCS["WGS 84"]',
    )
    from .hashing import sha256_of_file

    datum_declared = bool(vertical_datum) and vertical_datum.strip().lower() not in {
        "unknown",
        "none",
        "-",
    }
    record = TerrainRecord(
        source=source,
        raster_version=raster_version,
        vertical_datum=vertical_datum if datum_declared else "unknown",
        datum_declared=datum_declared,
        resolution_m=float(resolution_m),
        retrieval_date=retrieval_date or datetime.now(timezone.utc).isoformat(),
        clipping_method=clipping_method,
        raster_sha256=sha256_of_file(Path(raster_path)),
        clip_sha256=sha256_of_file(clip_path),
        raster_path=str(raster_path).replace("\\", "/"),
        clip_path=str(clip_path).replace("\\", "/"),
        bbox_deg=[
            origin_x,
            origin_y + raster.pixel_size_y * crop.shape[0],
            origin_x + raster.pixel_size_x * crop.shape[1],
            origin_y,
        ],
        width_cells=crop.shape[1],
        height_cells=crop.shape[0],
        valid_cells=int(valid.size),
        masked_cells=masked,
        elevation_min_m=float(valid.min()) if valid.size else None,
        elevation_max_m=float(valid.max()) if valid.size else None,
        elevation_mean_m=float(valid.mean()) if valid.size else None,
        nodata=nodata,
        geo_ascii_params=raster.geo_ascii_params,
        usable_for_clearance=False,
        caveat=TERRAIN_CAVEAT,
        note=(
            "usable_for_clearance is fixed false by design: even with a declared datum this "
            "is a ground surface at "
            f"{resolution_m} m, and a route that clears the ground does not clear the airspace."
        ),
        extra={
            "resolution_degrees": abs(raster.pixel_size_x),
            "raster_source_nodata": raster.nodata,
            "boundary_relation_covered": bool(mask.intersects(_as_polygon_or_multi(mask))),
        },
    )
    if not datum_declared:
        record.extra["datum_action_required"] = (
            "Declare the vertical datum before this clip can be used for any AGL conversion."
        )
    return record


def clearance_guard(record: TerrainRecord) -> None:
    """Raise unless the clip may legitimately feed a clearance calculation.

    Nothing this adapter produces may: a 30 m grid is the ground, and a tower, a wire or
    a rooftop is not the ground. ``clip_dem`` therefore always writes
    ``usable_for_clearance=False``, and this guard is what fails the build if a record is
    ever promoted to clearance-usable by hand, or if its vertical datum is undeclared.
    The refusal is a checked invariant, not a comment.
    """
    if record.usable_for_clearance:
        raise VerticalDatumError(
            "a terrain clip was marked usable for clearance; this project has no such source"
        )
    if not record.datum_declared:
        raise VerticalDatumError(
            f"vertical datum is {record.vertical_datum!r}; ground heights cannot be "
            "converted to above-ground level without it"
        )


def _apply_polygon_mask(
    crop: np.ndarray,
    mask: BaseGeometry,
    origin_x: float,
    origin_y: float,
    pixel_x: float,
    pixel_y: float,
    nodata: float,
    *,
    centre_only: bool,
) -> np.ndarray:
    import shapely

    rows, cols = crop.shape
    xs = origin_x + (np.arange(cols) + (0.0 if centre_only else 0.5)) * pixel_x
    ys = origin_y - (np.arange(rows) + (0.0 if centre_only else 0.5)) * abs(pixel_y)
    grid_x, grid_y = np.meshgrid(xs, ys)
    points = shapely.points(np.column_stack([grid_x.ravel(), grid_y.ravel()]))
    inside = shapely.contains(mask, points)
    masked = crop.copy()
    masked[~inside.reshape(rows, cols)] = nodata
    return masked


def _as_polygon_or_multi(geometry: BaseGeometry) -> BaseGeometry:
    return geometry


def summarise(records: list[TerrainRecord], path: Path) -> dict[str, Any]:
    payload = {
        "terrain_clips": [record.as_dict() for record in records],
        "caveat": TERRAIN_CAVEAT,
        "statement": "Simulation only. Not authorised for flight.",
        "authoritative": False,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        yaml.safe_dump(payload, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8"
    )
    return payload
